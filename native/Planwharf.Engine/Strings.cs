    static readonly Dictionary<string, string> English = Italian.Keys.ToDictionary(key => key, key => key, StringComparer.Ordinal);

    static string language = "en";
    public static string CurrentLanguage
    {
        get => language;
        set => language = IsItalian(value) ? "it" : "en";
    }

    // The picker stores "en" or "it". A saved tag such as "IT" or "it-IT" still selects Italian.
    static bool IsItalian(string? value)
    {
        var token = value?.Trim().Replace('_', '-');
        return token != null && (token.Equals("it", StringComparison.OrdinalIgnoreCase) || token.StartsWith("it-", StringComparison.OrdinalIgnoreCase));
    }

    public static CultureInfo Culture => CultureInfo.GetCultureInfo(CurrentLanguage == "it" ? "it-IT" : "en-US");

    public static string T(string key) => Lookup(key, CurrentLanguage == "it");

    // One language snapshot, so the template and the culture cannot come from different languages.
    public static string Format(string key, params object?[] args)
    {
        var italian = CurrentLanguage == "it";
        return string.Format(CultureInfo.GetCultureInfo(italian ? "it-IT" : "en-US"), Lookup(key, italian), args);
    }

    static string Lookup(string key, bool italian) =>
        italian && Italian.TryGetValue(key, out var translated) ? translated :
        English.TryGetValue(key, out var original) ? original : key;
