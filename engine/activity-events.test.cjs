'use strict';
const assert = require('node:assert/strict');
const { activityEvents, activityMessages, activityCapabilities, interpretActivity } = require('./activity.cjs');
const { LIMITS, sanitize } = require('./activity-events.cjs');
const event = (row, context) => activityEvents(JSON.stringify(row), context)[0];
const codex = { providerId: 'configured-codex', adapter: 'codex', model: 'exact-model' };
const start = event({ type: 'item.started', item: { type: 'command_execution', command: 'npm test' } }, codex);
assert.equal(start.provider, 'configured-codex');
assert.equal(start.adapter, 'codex');
assert.equal(start.model, 'exact-model');
assert.equal(start.protocol, 'item-events');
assert.equal(start.classification, 'test');
assert.equal(start.provenance, 'observed');
assert.equal(start.validated, false);
assert.equal(event({ type: 'item.started', item: { type: 'command_execution', command: 'npm test' } }).provider, 'unknown', 'Shared item protocol never silently identifies the provider');
const finished = event({ type: 'item.completed', item: { type: 'command_execution', command: 'npm test', exit_code: 0, aggregated_output: 'secret source code' } });
assert.equal(finished.state, 'finished');
assert.equal(finished.validated, false);
assert.equal(finished.technical.exitCode, 0);
assert.doesNotMatch(JSON.stringify(finished), /secret source code|passed|validated evidence/);
const failed = event({ type: 'item.completed', item: { type: 'command_execution', command: 'npm test', exit_code: 3 } });
assert.equal(failed.state, 'failed');
assert.equal(failed.classification, 'warning');
const report = event({ type: 'item.completed', item: { type: 'agent_message', text: '5 passed in 0.2s' } });
assert.equal(report.provenance, 'reported');
assert.equal(report.validated, false);
assert.equal(report.classification, 'test');
const agy = event({ event: 'step_update', step_update: { step_type: 'tool', state: 'DONE', tool_name: 'write_to_file', tool_info: { parameters: { TargetFile: '/private/feature.ts', CodeContent: 'confidential source' } } } }, { provider: 'antigravity' });
assert.equal(agy.classification, 'working');
assert.equal(agy.state, 'finished');
assert.equal(agy.technical.tool, 'write_to_file');
assert.doesNotMatch(JSON.stringify(agy), /confidential source|\/private/);
const block = event({ type: 'content_block_start', content_block: { type: 'tool_use', name: 'read_file', input: { path: '/private/config.js' } } }, { provider: 'grok' });
assert.equal(block.protocol, 'message-events');
assert.equal(block.classification, 'read');
for (const [name, classification] of [['Read', 'read'], ['Write', 'working'], ['Edit', 'working'], ['Glob', 'read'], ['Bash', 'test']]) {
  const translated = event({ type: 'assistant', message: { content: [{ type: 'tool_use', name, input: { file_path: '/private/fixture.txt', content: 'PRIVATE-FILE-CONTENT', command: 'node --test' } }] } }, { provider: 'claude' });
  assert.equal(translated.classification, classification);
  assert.equal(translated.provenance, 'observed'); assert.equal(translated.validated, false);
  assert.doesNotMatch(JSON.stringify(translated), /PRIVATE-FILE-CONTENT/);
}
assert.equal(activityCapabilities({ adapter: 'claude' }).expectedFormat, 'stream-json');
assert.equal(event({ type: 'item.started', item: { type: 'command_execution', command: 'node --test' } }, { adapter: 'claude' }).provenance, 'unknown');
const itemShape = { type: 'item.started', item: { type: 'command_execution', command: 'npm test' } };
assert.equal(event(itemShape, { adapter: 'antigravity' }).provenance, 'unknown');
assert.equal(event({ event: 'step_update', step_update: { step_type: 'tool', tool_name: 'run_command', parameters: { command: 'npm test' } } }, { adapter: 'codex' }).provenance, 'unknown');
assert.equal(event({ type: 'content_block_start', content_block: { type: 'tool_use', name: 'read_file', input: {} } }, { adapter: 'api' }).provenance, 'unknown');
for (const command of ['echo npm test', 'printf "pytest"', 'node -e "console.log(\'npm test\')"', 'cat test-fixture.js', 'echo tsc', 'echo Get-Content config.js', 'echo git diff']) {
  const translated = event({ type: 'item.started', item: { type: 'command_execution', command } }, codex);
  assert.notEqual(translated.classification, 'test');
  if (command.startsWith('echo') || command.startsWith('printf') || command.startsWith('node -e')) assert.equal(translated.classification, 'unknown');
}
for (const command of ['pytest', 'npm test', 'npm run test', 'node --test', 'node engine/parser.test.cjs', 'node test-worker.js']) {
  assert.equal(event({ type: 'item.started', item: { type: 'command_execution', command } }, codex).classification, 'test');
}
const api = event({ type: 'item.started', item: { type: 'command_execution', command: 'read_file' } }, { providerId: 'local-api', adapter: 'api' });
assert.equal(api.provider, 'local-api');
assert.equal(api.classification, 'unknown', 'API bridge omits input and emits tool name as command; do not infer target or completion');
assert.equal(activityCapabilities({ adapter: 'api' }).expectedFormat, 'planwharf-api-bridge');
assert.equal(activityCapabilities({ adapter: 'codex' }).detailedEventsExpected, false);
assert.equal(activityCapabilities({ adapter: 'grok' }).expectedFormat, 'plain');
assert.equal(activityCapabilities({ adapter: 'codex', lead: true }).expectedFormat, 'json');
assert.equal(activityCapabilities({ adapter: 'grok', lead: true }).liveDeliveryVerified, false);
assert.equal(activityCapabilities({ adapter: 'unknown' }).expectedFormat, 'unknown');
assert.equal(activityCapabilities({ adapter: 'antigravity' }).detailedEventsExpected, true);
for (const row of [null, [], { type: 'new-provider-event', secret: 'do not display' }, { type: 'assistant', message: { content: 'invalid' } }, { type: 'item.completed', item: { type: 'file_change', changes: {} } }]) {
  const translated = event(row);
  assert.equal(translated.classification, 'unknown');
  assert.equal(translated.validated, false);
  assert.doesNotMatch(JSON.stringify(translated), /do not display|invalid/);
}
assert.equal(event({ type: 'turn.failed', error: { message: 'secret error body' } }).state, 'failed');
assert.doesNotMatch(JSON.stringify(event({ type: 'turn.failed', error: { message: 'secret error body' } })), /secret error body/);
assert.equal(event({ event: 'result', result: { status: 'ERROR' } }).state, 'failed');
assert.equal(event({ event: 'result', result: { status: 'SUCCESS' } }).validated, false);
assert.equal(event({ type: 'result', result: 'Tests pass' }).provenance, 'reported');
const secrets = 'api_key=supersecret password="two words" Bearer abc123 sk-123456789 ghp_123456789 https://user:pass@example.invalid <script>alert(1)</script>\x1b[31m';
const safe = sanitize(secrets);
assert.doesNotMatch(safe, /supersecret|two words|abc123|123456789|user:pass|<script>|\x1b/);
assert.match(safe, /REDACTED/);
assert.doesNotMatch(sanitize('"api_key": "private-value" token=other-private'), /private-value|other-private/);
assert.doesNotMatch(sanitize('-----BEGIN PRIVATE KEY-----\nprivate material\n-----END PRIVATE KEY-----'), /private material/);
assert.doesNotMatch(activityMessages('Worker update api_key=supersecret')[0], /supersecret/);
const history = activityEvents(Array.from({ length: 500 }, (_, i) => 'update ' + i).join('\n'));
assert.equal(history.length, LIMITS.events);
assert.match(history[0].friendly, /300$/);
assert.ok(activityEvents('x'.repeat(LIMITS.line + 1))[0].classification === 'unknown');
assert.equal(activityEvents('x'.repeat(LIMITS.tail + 1) + '\nReading config.js').at(-1).friendly, 'Reading config.js');
assert.equal(activityEvents('{"event":"step_update","step_update":{"tool_name":"write_file"')[0].provenance, 'unknown');
assert.match(interpretActivity('Running tests', null, false), /^Stopped/);
assert.equal(activityEvents('Worker text')[0].provenance, 'reported');
assert.ok(activityEvents('x'.repeat(1000))[0].friendly.length <= LIMITS.text);
assert.equal('timestamp' in start, false, 'No fabricated event timestamps');
console.log('OK: structured activity provenance, provider identity, conservative capabilities, failure/completion separation, redaction, malformed protocols and bounded history. Fixture validation only; no live provider delivery.');
